import { formatMoney } from '../../lib/money.js';
import { monthLabel } from '../../lib/dates.js';

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

export const BASE_CSS = `
  @import url('https://fonts.googleapis.com/css2?family=Noto+Sans:wght@400;600&family=Noto+Sans+Devanagari:wght@400;600&display=swap');
  * { box-sizing: border-box; }
  body { font-family: 'Noto Sans', 'Noto Sans Devanagari', 'Lohit Devanagari', sans-serif; color: #1f2933; font-size: 12px; margin: 0; }
  .brand { color: #2BB673; font-weight: 600; font-size: 18px; }
  h1 { font-size: 16px; margin: 4px 0; }
  table { width: 100%; border-collapse: collapse; margin-top: 8px; }
  th, td { border: 1px solid #d9e2ec; padding: 5px 6px; text-align: left; vertical-align: top; }
  th { background: #e9f7f0; }
  .num { text-align: right; white-space: nowrap; }
  .muted { color: #627d98; font-size: 10px; }
  .total td { font-weight: 600; background: #f0fbf6; }
  .hdr { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #2BB673; padding-bottom: 6px; }
`;

export function payslipHtml(p: any, company: { name: string; currency: string; address?: string | null }) {
  const m = (x: number) => formatMoney(x, company.currency);
  const earnings = p.lines.filter((l: any) => l.kind === 'earning');
  const deductions = p.lines.filter((l: any) => l.kind === 'deduction');
  const s = p.summary ?? {};
  const row = (l: any) => `<tr><td>${esc(l.label.en)}<br/><span class="muted">${esc(l.label.hi)}</span><br/><span class="muted">${esc(l.explanation.en)}</span><br/><span class="muted">${esc(l.explanation.hi)}</span></td><td class="num">${m(l.amountPaise)}</td></tr>`;
  return `<!doctype html><html><head><meta charset="utf-8"/><style>${BASE_CSS}</style></head><body>
  <div class="hdr"><div><div class="brand">StaffMint</div><h1>${esc(company.name)}</h1><div class="muted">${esc(company.address ?? '')}</div></div>
  <div style="text-align:right"><h1>Payslip / वेतन पर्ची</h1><div>${esc(monthLabel(p.month, 'en'))} · ${esc(monthLabel(p.month, 'hi'))}</div>${p.revision > 1 ? `<div class="muted">Revision ${p.revision}</div>` : ''}</div></div>
  <table><tr><th>Employee / कर्मचारी</th><td>${esc(p.employeeName)}</td><th>Phone</th><td>${esc(p.employeePhone ?? '')}</td></tr>
  <tr><th>Salary / वेतन</th><td>${m(p.ratePaise)} ${p.wageType === 'daily' ? '/ day (दैनिक)' : '/ month (मासिक)'}</td><th>Payable days / देय दिन</th><td>${p.payableDays}${p.wageType === 'monthly' ? ` / ${p.divisor}` : ''}</td></tr></table>
  <table><tr><th>Present<br/>हाज़िर</th><th>Half day<br/>आधा दिन</th><th>Absent<br/>गैरहाज़िर</th><th>Paid leave<br/>सवेतन छुट्टी</th><th>Unpaid leave<br/>बिना वेतन</th><th>Holidays<br/>त्योहार</th><th>Week off<br/>साप्ताहिक</th></tr>
  <tr><td>${s.present ?? 0}</td><td>${s.halfDay ?? 0}</td><td>${s.absent ?? 0}</td><td>${s.paidLeave ?? 0}</td><td>${s.unpaidLeave ?? 0}</td><td>${s.holidays ?? 0}</td><td>${s.weekOffs ?? 0}</td></tr></table>
  <table><tr><th>Earnings / कमाई</th><th class="num">Amount</th></tr>${earnings.map(row).join('')}<tr class="total"><td>Gross / कुल कमाई</td><td class="num">${m(p.grossPaise)}</td></tr></table>
  <table><tr><th>Deductions / कटौती</th><th class="num">Amount</th></tr>${deductions.map(row).join('') || '<tr><td>None / कोई नहीं</td><td class="num">-</td></tr>'}<tr class="total"><td>Total deductions / कुल कटौती</td><td class="num">${m(p.deductionsPaise)}</td></tr></table>
  <table><tr class="total"><td style="font-size:14px">Net pay / हाथ में वेतन</td><td class="num" style="font-size:14px">${m(p.netPaise)}</td></tr></table>
  <p class="muted">Generated by StaffMint. Questions? Ask your employer or reply "Meri salary kam kyun?" on WhatsApp.</p>
  </body></html>`;
}

export function tableReportHtml(title: string, company: string, headers: string[], rows: (string | number)[][], subtitle = '') {
  return `<!doctype html><html><head><meta charset="utf-8"/><style>${BASE_CSS} td,th{font-size:10px}</style></head><body>
  <div class="hdr"><div><div class="brand">StaffMint</div><h1>${esc(company)}</h1></div><div style="text-align:right"><h1>${esc(title)}</h1><div class="muted">${esc(subtitle)}</div></div></div>
  <table><tr>${headers.map((h) => `<th>${esc(h)}</th>`).join('')}</tr>${rows.map((r) => `<tr>${r.map((c) => `<td${typeof c === 'number' ? ' class="num"' : ''}>${esc(c)}</td>`).join('')}</tr>`).join('')}</table>
  </body></html>`;
}
